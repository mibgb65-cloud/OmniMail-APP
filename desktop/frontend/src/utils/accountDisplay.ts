export function extractEmailDomain(email: string): string {
  const clean = email.trim().toLowerCase();
  const at = clean.lastIndexOf("@");
  return at >= 0 && at < clean.length - 1 ? clean.slice(at + 1) : "";
}

export function extractEmailLocalPart(email: string): string {
  const clean = email.trim().toLowerCase();
  const at = clean.indexOf("@");
  return at > 0 ? clean.slice(0, at) : clean;
}

export function resolveConciseProviderLabel(
  provider: ProviderId,
  email = "",
  lang: LanguageCode = "zh-CN",
): string {
  if (provider === "imap") {
    return extractEmailDomain(email) || "IMAP";
  }
  const entry = CONCISE_PROVIDER_LABELS[provider];
  if (!entry) {
    return extractEmailDomain(email) || "IMAP";
  }
  return lang === "en-US" ? entry.en : entry.zh;
}

export function isLegacyAutoGeneratedAccountName(
  rawName: string,
  email = "",
): boolean {
  const trimmed = rawName.trim();
  if (!trimmed) return true;
  const lower = trimmed.toLowerCase();
  if (LEGACY_AUTO_PREFIXES.has(lower)) return true;

  const dotIdx = trimmed.indexOf("·");
  if (dotIdx > 0) {
    const prefix = trimmed.slice(0, dotIdx).trim().toLowerCase();
    const suffix = trimmed.slice(dotIdx + 1).trim();
    if (LEGACY_AUTO_PREFIXES.has(prefix) && suffix.length > 0) {
      return true;
    }
  }
  void email;
  return false;
}

export function resolveSidebarAccountTitle(
  account: Pick<EmailAccount, "name" | "provider" | "email">,
  lang: LanguageCode = "zh-CN",
): string {
  const raw = account.name?.trim() ?? "";
  if (!raw || isLegacyAutoGeneratedAccountName(raw, account.email)) {
    return resolveConciseProviderLabel(account.provider, account.email, lang);
  }
  if (account.provider !== "imap") {
    const entry = CONCISE_PROVIDER_LABELS[account.provider];
    if (entry && (raw === entry.zh || raw === entry.en)) {
      return lang === "en-US" ? entry.en : entry.zh;
    }
  }
  return raw;
}

export function buildAccountNameSuggestions(
  provider: ProviderId,
  email: string,
  lang: LanguageCode = "zh-CN",
): string[] {
  const isEn = lang === "en-US";
  const concise = resolveConciseProviderLabel(provider, email, lang);
  const domain = extractEmailDomain(email);
  const domainStem = domain ? domain.split(".")[0] : "";
  const capStem = domainStem
    ? domainStem.charAt(0).toUpperCase() + domainStem.slice(1)
    : "";

  const candidates = [
    concise,
    isEn ? "Work Mail" : "公司工作邮",
    capStem && capStem.length >= 2 ? capStem : domain,
    provider === "tencent_exmail"
      ? isEn
        ? "WeCom Mail"
        : "企微工作邮"
      : provider === "imap"
        ? isEn
          ? "Tencent Exmail"
          : "腾讯企业邮"
        : isEn
          ? "Team Mail"
          : "团队邮箱",
    provider === "imap" ? (isEn ? "Alibaba Mail" : "阿里企业邮") : domain,
  ];

  const unique: string[] = [];
  for (const item of candidates) {
    const clean = (item ?? "").trim().slice(0, ACCOUNT_NAME_MAX_LEN);
    if (clean && !unique.includes(clean)) {
      unique.push(clean);
    }
    if (unique.length >= 4) break;
  }
  return unique;
}
